// `bun run schema:lock` — record the columns /export serves in schema.lock.json.
//
// The lock is what layers/terminal/test/terminal-dictionary.test.ts holds the
// exports to, so it is only rewritten when the newest release in
// layers/terminal/server/utils/data-schema.ts accounts for every column that
// moved since the last lock (lockRefusal). Run it after adding a release, and
// commit what it writes.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import {
  SCHEMA_VERSION,
  lockRefusal,
  type SchemaLock,
} from '../layers/terminal/server/utils/data-schema'
import { EXPORT_TABLES } from '../layers/terminal/server/utils/terminal-export'

const LOCK_FILE = join(import.meta.dir, '..', 'schema.lock.json')

const columns = Object.fromEntries(
  Object.values(EXPORT_TABLES).map((table) => [table.name, [...table.columns]]),
)
const next: SchemaLock = { schema_version: SCHEMA_VERSION, tables: columns }

if (existsSync(LOCK_FILE)) {
  const lock = JSON.parse(readFileSync(LOCK_FILE, 'utf8')) as SchemaLock
  const refusal = lockRefusal(lock, columns)
  if (refusal) {
    console.error(`schema:lock — not written. ${refusal}.`)
    process.exit(1)
  }
}

writeFileSync(
  LOCK_FILE,
  `${JSON.stringify(
    {
      _comment:
        'Generated by `bun run schema:lock`: the columns /export serves at schema_version. The dictionary test fails when they drift. Commit it.',
      ...next,
    },
    null,
    2,
  )}\n`,
)
console.info(`schema:lock — schema.lock.json at ${SCHEMA_VERSION}`)
